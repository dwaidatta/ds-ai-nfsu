"""Build the GitHub Pages site into _site/.

Copies index.html and quiz/, converts every notebook in Notebooks/ to HTML and
fills the Study Notebooks list in index.html from those notebooks.
"""
import html
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "_site"
NOTEBOOKS = ROOT / "Notebooks"
MARKER = "<!-- NOTEBOOKS: generated by scripts/build_site.py from the Notebooks folder -->"
EMOJI = re.compile("[\U0001F000-\U0001FFFF☀-➿️]")


def notebook_title(path: Path) -> str:
    """First '# ' heading of the notebook, falling back to the file name."""
    nb = json.loads(path.read_text(encoding="utf-8"))
    for cell in nb["cells"]:
        if cell["cell_type"] != "markdown":
            continue
        for line in "".join(cell["source"]).splitlines():
            if line.startswith("# "):
                return EMOJI.sub("", line[2:]).strip()
    return path.stem.replace("_", " ")


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    shutil.copy(ROOT / "index.html", OUT / "index.html")
    shutil.copytree(ROOT / "quiz", OUT / "quiz")
    (OUT / ".nojekyll").touch()

    notebooks = sorted(NOTEBOOKS.glob("*.ipynb"))
    subprocess.run(
        [
            sys.executable, "-m", "nbconvert", "--to", "html",
            "--template", "colab", "--template-file", "index.html.j2",
            "--TemplateExporter.extra_template_basedirs=nbtemplate",
            "--output-dir", str(OUT / "notebooks-html"),
            *map(str, notebooks),
        ],
        cwd=ROOT,
        check=True,
    )

    entries = sorted((notebook_title(nb), nb.stem) for nb in notebooks)
    buttons = "\n".join(
        f'        <a class="resource-button" href="notebooks-html/{html.escape(stem)}.html">\n'
        f'          <span class="resource-label"><i class="bi bi-file-earmark-code"></i> {html.escape(title)}</span>\n'
        '          <i class="bi bi-arrow-right resource-arrow"></i>\n'
        "        </a>"
        for title, stem in entries
    )
    index = OUT / "index.html"
    text = index.read_text(encoding="utf-8")
    if MARKER not in text:
        sys.exit("NOTEBOOKS marker not found in index.html")
    index.write_text(text.replace(MARKER, buttons.lstrip()), encoding="utf-8")
    print(f"Built {OUT} with {len(entries)} notebooks")


if __name__ == "__main__":
    main()
