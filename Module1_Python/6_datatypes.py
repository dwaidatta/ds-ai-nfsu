# dictionary
# key : value
# keys must be unique
# keys should be immutable

d1 = {1: "Hello", 2: "World"}
d2 = {"Ram": [80, 85, 89], "Sam": [81, 90, 86]}

print(d1)
print(d1[1])
print(d2["Sam"])



