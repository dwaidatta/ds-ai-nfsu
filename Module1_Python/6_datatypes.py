# numeric data types

a = 5         # int
b = 5.0       # float
c = 2 + 4j    # complex numbers

print(type(a))
print(type(b))
print(type(c))



# sequence types
# can be accessed via indices

# string
s = "Hello Everyone 123" # sequence of characters
print(type(s))

# list
# separated by comma
# mutable
# third bracket
